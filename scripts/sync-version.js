/**
 * sync-version.js
 * Reads the canonical version and date from about/about.csv
 * and synchronizes them into wails.json and frontend/package.json.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, '..');

/**
 * Parses about.csv taking quoted values (e.g. "October 12, 2026") into account.
 * @param {string} content
 * @returns {Record<string, string>}
 */
function parseAboutCSV(content) {
  const cleaned = content.replace(/^\uFEFF/, '');
  const lines = cleaned.split(/\r?\n/);
  const data = {};

  for (const line of lines) {
    if (!line.trim()) continue;
    const match = line.match(/^([^,]+),("([^"]+)"|[^,]*)(,.*)?$/);
    if (match) {
      const key = match[1].trim();
      const value = (match[3] !== undefined ? match[3] : match[2] || '').trim();
      data[key] = value;
    }
  }
  return data;
}

function sync() {
  const csvPath = resolve(rootDir, 'about', 'about.csv');
  if (!existsSync(csvPath)) {
    console.warn(`[sync-version] about.csv not found at ${csvPath}`);
    return;
  }

  const csvContent = readFileSync(csvPath, 'utf8');
  const metadata = parseAboutCSV(csvContent);
  const version = metadata['Version'];
  const versionDate = metadata['Version Date'];

  if (!version) {
    console.warn('[sync-version] No "Version" found in about/about.csv');
    return;
  }

  console.log(`[sync-version] Canonical Version: ${version} (${versionDate || 'No date'})`);

  // 1. Sync wails.json
  const wailsPath = resolve(rootDir, 'wails.json');
  if (existsSync(wailsPath)) {
    try {
      const wailsRaw = readFileSync(wailsPath, 'utf8');
      const wailsJson = JSON.parse(wailsRaw);
      if (!wailsJson.info) wailsJson.info = {};

      if (wailsJson.info.productVersion !== version) {
        wailsJson.info.productVersion = version;
        writeFileSync(wailsPath, JSON.stringify(wailsJson, null, 2) + '\n');
        console.log(`[sync-version] Updated wails.json productVersion -> ${version}`);
      }
    } catch (err) {
      console.error('[sync-version] Failed to update wails.json:', err);
    }
  }

  // 2. Sync frontend/package.json
  const pkgPath = resolve(rootDir, 'frontend', 'package.json');
  if (existsSync(pkgPath)) {
    try {
      const pkgRaw = readFileSync(pkgPath, 'utf8');
      const pkgJson = JSON.parse(pkgRaw);

      if (pkgJson.version !== version) {
        pkgJson.version = version;
        writeFileSync(pkgPath, JSON.stringify(pkgJson, null, 2) + '\n');
        console.log(`[sync-version] Updated frontend/package.json version -> ${version}`);
      }
    } catch (err) {
      console.error('[sync-version] Failed to update frontend/package.json:', err);
    }
  }

  // 3. Sync frontend/package-lock.json if present
  const pkgLockPath = resolve(rootDir, 'frontend', 'package-lock.json');
  if (existsSync(pkgLockPath)) {
    try {
      const lockRaw = readFileSync(pkgLockPath, 'utf8');
      const lockJson = JSON.parse(lockRaw);
      let changed = false;

      if (lockJson.version !== version) {
        lockJson.version = version;
        changed = true;
      }
      if (lockJson.packages && lockJson.packages[''] && lockJson.packages[''].version !== version) {
        lockJson.packages[''].version = version;
        changed = true;
      }

      if (changed) {
        writeFileSync(pkgLockPath, JSON.stringify(lockJson, null, 2) + '\n');
        console.log(`[sync-version] Updated frontend/package-lock.json version -> ${version}`);
      }
    } catch (err) {
      console.error('[sync-version] Failed to update frontend/package-lock.json:', err);
    }
  }

  // 4. Generate frontend/src/version.js
  const versionJsPath = resolve(rootDir, 'frontend', 'src', 'version.js');
  try {
    const versionJsContent = `// This file is auto-generated by scripts/sync-version.js
// Do not edit manually. Edit about/about.csv instead.
export const APP_VERSION = ${JSON.stringify(version)};
export const APP_VERSION_DATE = ${JSON.stringify(versionDate || '')};
`;
    let shouldWrite = true;
    if (existsSync(versionJsPath)) {
      const existing = readFileSync(versionJsPath, 'utf8');
      if (existing === versionJsContent) {
        shouldWrite = false;
      }
    }
    if (shouldWrite) {
      writeFileSync(versionJsPath, versionJsContent);
      console.log(`[sync-version] Updated frontend/src/version.js -> ${version} (${versionDate || 'No date'})`);
    }
  } catch (err) {
    console.error('[sync-version] Failed to update frontend/src/version.js:', err);
  }
}

sync();

